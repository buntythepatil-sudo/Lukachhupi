export function getPresetById(id: string): CharacterPreset {
  return (
    VILLAGE_CHARACTER_PRESETS.find((p) => p.id === id) ??
    VILLAGE_CHARACTER_PRESETS[0]
  );
}

export function createCustomizationFromPreset(
  preset: CharacterPreset,
): CharacterCustomization {
  return {
    presetId: preset.id,
    name: preset.defaultName,
    outfitStyle: preset.outfitStyle,
    outfitColor: preset.outfitColor,
    accessory: preset.accessory,
  };
}
